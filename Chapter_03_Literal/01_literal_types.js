// literal is a value assigned to variable

// String literal
let name = "John";

// Number literal
let age = 25;

// Boolean literal
let isActive = true;

// BigInt literal
let bigNumber = 123n;

// Null literal
let empty = null;

// Undefined literal (value is undefined)
let notAssigned = undefined;

// Object literal
let person = {
  firstName: "John",
  lastName: "Doe"
};

// Array literal
let numbers = [1, 2, 3];